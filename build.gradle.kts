// Domain registry: tools/domain-registry/registry.json is the single source of the hosts each server
// routes without a network request. `generateHostRegistry` writes one <Service>Hosts.kt per server module;
// `checkHostRegistry` fails when those files are out of date.
abstract class HostRegistryTask : DefaultTask() {
    @get:InputFile
    abstract val registry: RegularFileProperty

    @get:Internal
    abstract val rootDirectory: DirectoryProperty

    protected fun render(): Map<File, String> {
        @Suppress("UNCHECKED_CAST")
        val json = groovy.json.JsonSlurper().parse(registry.get().asFile) as Map<String, Any?>
        val root = rootDirectory.get().asFile
        @Suppress("UNCHECKED_CAST")
        return (json["services"] as List<Map<String, Any?>>).associate { service ->
            val pkg = service["package"] as String
            val name = service["object"] as String
            @Suppress("UNCHECKED_CAST")
            val hosts = (service["hosts"] as List<Map<String, Any?>>).filter { it["routed"] == true }
            @Suppress("UNCHECKED_CAST")
            val subdomains = service["subdomainsOf"] as List<String>
            @Suppress("UNCHECKED_CAST")
            val families = service["families"] as List<Map<String, String>>
            val text = buildString {
                appendLine("// GENERATED by `./gradlew generateHostRegistry` from tools/domain-registry/registry.json. Do not edit.")
                appendLine("package $pkg")
                appendLine()
                appendLine("import com.ead.lib.moongetter.resolution.HostSet")
                appendLine()
                appendLine("/** Hosts routed to ${service["service"]} without a network request (researched ${json["researchedAt"]}). */")
                appendLine("internal object $name {")
                appendLine("    val hostSet: HostSet = HostSet(")
                appendLine("        exact = listOf(")
                hosts.forEach { appendLine("            \"${it["host"]}\", // ${it["reason"]}") }
                appendLine("        ),")
                appendLine("        subdomainsOf = listOf(")
                subdomains.forEach { appendLine("            \"$it\",") }
                appendLine("        ),")
                appendLine("        families = listOf(")
                families.forEach { appendLine("            \"\"\"${it["pattern"]}\"\"\", // ${it["reason"]}") }
                appendLine("        ),")
                appendLine("    )")
                appendLine("}")
            }
            File(root, "${service["module"]}/src/commonMain/kotlin/${pkg.replace('.', '/')}/$name.kt") to text
        }
    }
}

abstract class GenerateHostRegistry : HostRegistryTask() {
    @TaskAction
    fun generate() = render().forEach { (file, text) ->
        file.parentFile.mkdirs()
        file.writeText(text)
    }
}

abstract class CheckHostRegistry : HostRegistryTask() {
    @TaskAction
    fun check() {
        val stale = render().filter { (file, text) -> !file.exists() || file.readText() != text }.keys
        if (stale.isNotEmpty()) throw GradleException(
            "Host lists are out of date, run ./gradlew generateHostRegistry:\n" + stale.joinToString("\n")
        )
    }
}

tasks.register<GenerateHostRegistry>("generateHostRegistry") {
    group = "moongetter"
    description = "Writes each server module's host list from tools/domain-registry/registry.json."
    registry.set(layout.projectDirectory.file("tools/domain-registry/registry.json"))
    rootDirectory.set(layout.projectDirectory)
}

tasks.register<CheckHostRegistry>("checkHostRegistry") {
    group = "verification"
    description = "Fails when a server module's host list differs from tools/domain-registry/registry.json."
    registry.set(layout.projectDirectory.file("tools/domain-registry/registry.json"))
    rootDirectory.set(layout.projectDirectory)
}
